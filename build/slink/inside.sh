#!/bin/sh
# SPDX-License-Identifier: MIT
# Runs INSIDE the pinned Debian slink (i386) container. Builds the reference
# cc1psx and cccp exactly as the historical toolchain did, and collects the
# generated build-time sources.
#
# Mounts (see build-reference.sh):
#   /mount   pinned homebrew-psyq checkout (read-only use; copied to tmpfs)
#   /build   this repository's build/ directory (read-only)
#   /result  output directory
#
# Environment: SLINK_PACKAGES, GCC_SUBDIR, CC1_VERSION_BANNER, CPP_VERSION_BANNER
# (from pins.env).
set -e

# --- toolchain ---------------------------------------------------------------
# dpkg 1.4 cannot run under QEMU user emulation ("cannot scan updates
# directory: Invalid argument"), so download with apt and unpack the .deb files
# directly. Package contents are identical to what dpkg would install.
apt-get update
apt-get install -y -d $SLINK_PACKAGES || true
for d in /var/cache/apt/archives/*.deb; do dpkg-deb -x "$d" /; done
gcc --version | head -1
bison --version | head -1
gperf --version 2>&1 | head -1
autoconf --version | head -1

# --- source on tmpfs ----------------------------------------------------------
# glibc 2.0's getcwd() fails on Docker bind mounts, which breaks configure.
mkdir -p /work/src && cp -a "/mount/$GCC_SUBDIR" /work/src/
cp /mount/VERSION /work/src/VERSION
SRC=/work/src/$GCC_SUBDIR/gcc
BUILD=/work/build
mkdir -p "$BUILD"

# --- configure + build (matches homebrew-psyq/build-scripts) -----------------
cd "$SRC" && autoconf && autoheader
cd "$BUILD"
"$SRC/configure" --target=mips-psx --host=i686-pc-linux
make cc1 CFLAGS="-O2 -g"
make cpp CFLAGS="-O2 -g"

# --- parser regeneration exactly as gcc/Makefile.in does ---------------------
mkdir -p /work/parse && cp "$SRC/c-parse.in" "$SRC/c-parse.gperf" /work/parse/
cd /work/parse
echo '/*WARNING: This file is automatically generated!*/' >tmp-c-parse.y
sed -e "/^ifobjc/,/^end ifobjc/d" -e "/^ifc/d" -e "/^end ifc/d" c-parse.in >>tmp-c-parse.y
mv tmp-c-parse.y c-parse.y
bison -d c-parse.y -o c-parse.c
gperf -p -j1 -i 1 -g -o -t -G -N is_reserved_word -k1,3,$ c-parse.gperf >c-gperf.h

# --- collect ------------------------------------------------------------------
mkdir -p /result/gen
cp "$BUILD/cc1" /result/cc1psx
cp "$BUILD/cccp" /result/cccp
for f in auto-config.h bc-arity.h bc-opcode.h bc-opname.h config.h hconfig.h \
  insn-attr.h insn-attrtab.c insn-codes.h insn-config.h insn-emit.c insn-extract.c \
  insn-flags.h insn-opinit.c insn-output.c insn-peep.c insn-recog.c options.h \
  specs.h tconfig.h tm.h; do
  cp "$BUILD/$f" /result/gen/
done
cp /work/parse/c-parse.c /work/parse/c-parse.h /work/parse/c-gperf.h /result/gen/
# cexp.c is generated by `make cpp` into the source directory (gcc/Makefile.in).
cp "$SRC/cexp.c" /result/gen/

"$BUILD/cc1" -version </dev/null 2>/result/cc1-version.txt || true
cat /result/cc1-version.txt
if ! grep -F "$CC1_VERSION_BANNER" /result/cc1-version.txt >/dev/null; then
  echo "error: version banner mismatch" >&2
  exit 1
fi
# cccp has no -version switch; -v prints the banner and then reads stdin.
"$BUILD/cccp" -v </dev/null 2>/result/cccp-version.txt >/dev/null || true
cat /result/cccp-version.txt
if ! grep -F "$CPP_VERSION_BANNER" /result/cccp-version.txt >/dev/null; then
  echo "error: preprocessor version banner mismatch" >&2
  exit 1
fi
echo REFERENCE-BUILD-DONE
